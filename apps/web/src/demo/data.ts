const DAY = 86_400_000
const now = Date.now()

function at(offsetDays: number, hour = 12, minute = 0): string {
  const date = new Date(now + offsetDays * DAY)
  date.setHours(hour, minute, 0, 0)
  return date.toISOString()
}

